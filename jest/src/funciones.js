function suma(valor1, valor2) {
    return valor1 + valor2
}

function resta(valor1, valor2) {
    return valor1 - valor2
}

function multiplicar(valor1, valor2) {
    return valor1 * valor2
}

function dividir(valor1, valor2) {
    return valor1 * valor2
}

module.exports = {suma, resta, multiplicar, dividir};